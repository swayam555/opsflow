CREATE SEQUENCE ticket_seq START WITH 1001;

CREATE TABLE ticket (
    id                   BIGINT        PRIMARY KEY,
    ticket_key           VARCHAR(20)   NOT NULL UNIQUE,
    title                VARCHAR(200)  NOT NULL,
    description          VARCHAR(5000),
    reporter             VARCHAR(100),
    status               VARCHAR(16)   NOT NULL,
    priority             VARCHAR(10),
    owner_team           VARCHAR(60),
    priority_overridden  BOOLEAN       NOT NULL DEFAULT FALSE,
    team_overridden      BOOLEAN       NOT NULL DEFAULT FALSE,
    triage_reason        VARCHAR(600),
    triage_source        VARCHAR(10),
    triage_confidence    VARCHAR(10),
    triage_matched       VARCHAR(600),
    triage_note          VARCHAR(300),
    requested_workflow   VARCHAR(60),
    workflow_id          VARCHAR(60),
    workflow_name        VARCHAR(120),
    current_run_id       VARCHAR(36),
    run_status           VARCHAR(16),
    run_error            VARCHAR(1000),
    last_report          VARCHAR(80),
    created_by           VARCHAR(60)   NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    triaged_at           TIMESTAMP WITH TIME ZONE,
    actioned_at          TIMESTAMP WITH TIME ZONE,
    resolved_at          TIMESTAMP WITH TIME ZONE,
    version              BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX ix_ticket_created ON ticket (created_at);
CREATE INDEX ix_ticket_status ON ticket (status);

CREATE TABLE ticket_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   BIGINT        NOT NULL REFERENCES ticket (id),
    type        VARCHAR(30)   NOT NULL,
    message     VARCHAR(1500) NOT NULL,
    actor       VARCHAR(60)   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_event_ticket ON ticket_event (ticket_id, id);

CREATE TABLE job (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   BIGINT        NOT NULL REFERENCES ticket (id),
    type        VARCHAR(20)   NOT NULL,
    workflow    VARCHAR(60),
    rerun       BOOLEAN       NOT NULL DEFAULT TRUE,
    job_trigger VARCHAR(20)   NOT NULL,
    status      VARCHAR(10)   NOT NULL,
    attempts    INT           NOT NULL DEFAULT 0,
    next_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error  VARCHAR(600),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX ix_job_due ON job (status, next_at);
